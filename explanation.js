/**
 * ============================================================================
 * ? TypeScript with JavaScript Libraries
 * ============================================================================
 *
 * * Some JavaScript libraries do not include TypeScript type definitions.
 *
 * * When using such a library:
 *
 * * 1. Install the library normally.
 *
 *  npm i some-library
 *
 * * 2. Install its TypeScript type definitions as a development dependency.
 *
 *  npm i -D @types/some-library
 *
 * * The `@types` package provides TypeScript type definitions
 * * for JavaScript libraries.
 *
 * ============================================================================
 */